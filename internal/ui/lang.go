// SetLanguage cambia el idioma; "" lo elige por $LANG (español si empieza por
// "es", inglés si no).
func SetLanguage(l string) {
	if l == "" {
		l = "en"
		for _, v := range []string{os.Getenv("LC_ALL"), os.Getenv("LC_MESSAGES"), os.Getenv("LANG")} {
			if v != "" {
				if strings.HasPrefix(v, "es") {
					l = "es"
				}
				break
			}
		}
	}
	if _, ok := strs[l]; !ok {
		l = "en"
	}
	lang = l
}

// N es T para cantidades: con 1 usa la forma en singular (key_one), si existe.
func N(key string, n int) string {
	if n == 1 {
		if _, ok := strs[lang][key+"_one"]; ok {
			return T(key + "_one")
		}
	}
	return T(key, n)
}

// T devuelve el texto de key en el idioma en uso, con args si lleva formato.
func T(key string, args ...any) string {
	s, ok := strs[lang][key]
	if !ok {
		s = strs["en"][key]
	}
	if len(args) > 0 {
		return fmt.Sprintf(s, args...)
	}
	return s
}
